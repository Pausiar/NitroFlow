/** Every fix the one-click optimization knows how to apply (used to validate IPC input). */
export const SMART_FIX_IDS: readonly SmartFixId[] = [
  'cleanup_safe',
  'startup_disable_recommended',
  'power_plan_balanced',
  'empty_recycle_bin'
]

/**
 * Fixes that are safe even without a restore point: deleted temp files are
 * regenerated by Windows, startup toggles are recorded with an undo, the
 * power plan is a plain setting and emptying the bin is an explicit choice
 * that a restore point would not protect anyway. Anything that edits the
 * registry must NOT be added here.
 */
const SAFE_WITHOUT_RESTORE_POINT: ReadonlySet<SmartFixId> = new Set<SmartFixId>([
  'cleanup_safe',
  'startup_disable_recommended',
  'power_plan_balanced',
  'empty_recycle_bin'
])

const POWER_PLAN_BALANCED = '381b4222-f694-41f0-9685-ff5bb260df2e'
/** First block of the built-in "Power saver" plan GUID. */
const POWER_SAVER_PREFIX = 'a1841308'

/** Cleanup below this size is not worth bothering a user about. */
const CLEANUP_MIN_MB = 100
/** Recycle bin size from which we mention it. */
const RECYCLE_BIN_MIN_MB = 500
/** Cached cleanup scans are reused by "Optimizar ahora" for this long. */
const SCAN_CACHE_MS = 15 * 60_000

const SEVERITY_PENALTY: Record<HealthIssue['severity'], number> = {
  critical: 25,
  warning: 12,
  info: 4
}

export interface DriveSpace {
  drive: string
  freeGB: number
  totalGB: number
}

/** Something the IPC layer must record in the history (startup toggles need one entry each for undo). */
export type SmartActionEvent =
  | { kind: 'startup'; id: string; name: string }
  | { kind: 'cleanup'; freedMB: number; categoryIds: string[]; label: string }
  | { kind: 'power_plan' }

export interface HealthDependencies {
  cleanup: Pick<CleanupService, 'scan' | 'clean'>
  startup: Pick<StartupManager, 'listEntries' | 'toggleEntry'>
  restorePoint: Pick<RestorePointService, 'create'>
  ps: PowerShellRunner
  isAdmin: () => Promise<boolean>
  shouldCreateRestorePoint: () => boolean
  getMemory: () => { totalMB: number; freeMB: number }
  getSystemDrive: () => Promise<DriveSpace | null>
}

/** Formats megabytes the Spanish way: "850 MB", "2,3 GB". */
export function formatSize(mb: number): string {
  if (mb >= 1024) return `${(mb / 1024).toFixed(1).replace('.', ',')} GB`
  return `${Math.round(mb)} MB`
}

/** "A", "A y B", "A, B y 2 más". */
function listNames(names: string[], max = 3): string {
  if (names.length === 0) return ''
  if (names.length === 1) return names[0]
  if (names.length <= max) return `${names.slice(0, -1).join(', ')} y ${names[names.length - 1]}`
  return `${names.slice(0, max).join(', ')} y ${names.length - max} más`
}

async function defaultSystemDrive(): Promise<DriveSpace | null> {
  const drive = process.platform === 'win32' ? `${process.env.SystemDrive || 'C:'}\\` : '/'
  try {
    const s = await fs.promises.statfs(drive)
    const totalGB = (s.blocks * s.bsize) / 1024 ** 3
    const freeGB = (s.bavail * s.bsize) / 1024 ** 3
    if (!Number.isFinite(totalGB) || totalGB <= 0) return null
    return { drive: process.platform === 'win32' ? drive.slice(0, 2) : 'C:', freeGB, totalGB }
  } catch {
    return null
  }
}

/** The elevation check spawns PowerShell: do it once per run of the app. */
let elevatedPromise: Promise<boolean> | null = null
export function isAdminCached(): Promise<boolean> {
  if (!elevatedPromise) elevatedPromise = isElevated().catch(() => false)
  return elevatedPromise
}

function defaultDependencies(): HealthDependencies {
  return {
    cleanup: new CleanupService(),
    startup: new StartupManager(),
    restorePoint: new RestorePointService(),
    ps: runPowerShellResult,
    isAdmin: isAdminCached,
    shouldCreateRestorePoint: () => SettingsService.getInstance().get().createRestorePoints !== false,
    getMemory: () => ({ totalMB: os.totalmem() / 1024 / 1024, freeMB: os.freemem() / 1024 / 1024 }),
    getSystemDrive: defaultSystemDrive
  }
}

/** Startup entries that the one-click optimization is allowed to turn off. */
export function disableCandidates(entries: StartupEntry[]): StartupEntry[] {
  return entries.filter((e) => e.recommendation === 'disable' && !e.essential && e.enabled)
}

/** Categories cleaned by "Optimizar ahora": recommended ones only, never the recycle bin. */
function recommendedCategories(categories: CleanupCategory[]): CleanupCategory[] {
  return categories.filter((c) => c.recommended === true && c.id !== 'recycle_bin')
}

/**
 * Health check + one-click optimization for non-expert users.
 *
 * `scan()` never throws: every check runs independently and a failing one is
 * simply left out of the report. `smartOptimize()` applies only fixes that
 * cannot lose user data or break Windows.
 */
export class HealthService {
  private readonly deps: HealthDependencies
  private lastCleanupScan: { at: number; categories: CleanupCategory[] } | null = null

  constructor(deps: Partial<HealthDependencies> = {}) {
    this.deps = { ...defaultDependencies(), ...deps }
  }

  async scan(): Promise<HealthReport> {
    const safe = async <T>(name: string, fn: () => Promise<T>): Promise<T | null> => {
      try {
        return await fn()
      } catch (err) {
        log.warn(`HealthService: check "${name}" failed:`, err)
        return null
      }
    }

    const [isAdmin, cleanupIssues, startupIssue, powerIssue, diskIssue, ramIssue] = await Promise.all([
      safe('admin', () => this.deps.isAdmin()),
      safe('cleanup', () => this.checkCleanup()),
      safe('startup', () => this.checkStartup()),
      safe('power', () => this.checkPowerPlan()),
      safe('disk', () => this.checkDiskSpace()),
      safe('ram', async () => this.checkMemory())
    ])

    const issues: HealthIssue[] = [
      ...(cleanupIssues ?? []),
      startupIssue,
      powerIssue,
      diskIssue,
      ramIssue
    ].filter((i): i is HealthIssue => Boolean(i))

    // Most important first; within a severity, things we can fix first.
    const order: Record<HealthIssue['severity'], number> = { critical: 0, warning: 1, info: 2 }
    issues.sort((a, b) => order[a.severity] - order[b.severity] || Number(b.autoFix) - Number(a.autoFix))

    const score = computeScore(issues)
    return {
      score,
      issues,
      summary: buildSummary(score, issues),
      scannedAt: Date.now(),
      isAdmin: Boolean(isAdmin)
    }
  }

  // ── Checks ─────────────────────────────────────────────────────────────────

  private async getCleanupCategories(): Promise<CleanupCategory[]> {
    if (this.lastCleanupScan && Date.now() - this.lastCleanupScan.at < SCAN_CACHE_MS) {
      return this.lastCleanupScan.categories
    }
    const categories = await this.deps.cleanup.scan()
    this.lastCleanupScan = { at: Date.now(), categories }
    return categories
  }

  private async checkCleanup(): Promise<HealthIssue[]> {
    // A health scan must always show fresh numbers.
    this.lastCleanupScan = null
    const categories = await this.getCleanupCategories()
    const issues: HealthIssue[] = []

    const junkMB = recommendedCategories(categories).reduce((sum, c) => sum + (c.sizeMB || 0), 0)
    if (junkMB >= CLEANUP_MIN_MB) {
      issues.push({
        id: 'junk_files',
        title: 'Archivos temporales que ocupan espacio',
        description:
          `Hay ${formatSize(junkMB)} de archivos temporales y restos que Windows y tus programas ya no necesitan. ` +
          'Se pueden borrar sin riesgo: no se toca ningún documento, foto ni archivo personal.',
        severity: junkMB >= 2048 ? 'warning' : 'info',
        fixId: 'cleanup_safe',
        fixLabel: 'Borrar archivos temporales',
        autoFix: true,
        benefit: `${formatSize(junkMB)} libres`,
        page: 'cleanup'
      })
    }

    const bin = categories.find((c) => c.id === 'recycle_bin')
    if (bin && bin.sizeMB >= RECYCLE_BIN_MIN_MB) {
      issues.push({
        id: 'recycle_bin',
        title: 'La papelera de reciclaje está llena',
        description:
          `La papelera ocupa ${formatSize(bin.sizeMB)}. Vacíala solo si estás seguro de que no necesitas ` +
          'recuperar nada de lo que hay dentro: después no se podrá recuperar.',
        severity: 'info',
        fixId: 'empty_recycle_bin',
        fixLabel: 'Vaciar la papelera',
        autoFix: false,
        benefit: `${formatSize(bin.sizeMB)} libres`,
        page: 'cleanup'
      })
    }
    return issues
  }

  private async checkStartup(): Promise<HealthIssue | null> {
    const candidates = disableCandidates(await this.deps.startup.listEntries())
    if (candidates.length === 0) return null

    const seconds = candidates.reduce(
      (sum, e) => sum + (e.impact === 'High' ? 5 : e.impact === 'Medium' ? 3 : 1),
      0
    )
    const n = candidates.length
    return {
      id: 'startup_programs',
      title: n === 1 ? 'Un programa ralentiza el encendido' : `${n} programas ralentizan el encendido`,
      description:
        `${listNames(candidates.map((e) => e.name))} se ${n === 1 ? 'abre' : 'abren'} solo${n === 1 ? '' : 's'} ` +
        'cada vez que enciendes el PC y lo hacen más lento. Se pueden desactivar sin problema: ' +
        'seguirán funcionando cuando los abras tú, y puedes volver a activarlos cuando quieras.',
      severity: n >= 3 ? 'warning' : 'info',
      fixId: 'startup_disable_recommended',
      fixLabel: n === 1 ? 'Desactivar este programa al inicio' : `Desactivar ${n} programas al inicio`,
      autoFix: true,
      benefit: `~${seconds} s menos de arranque`,
      page: 'startup'
    }
  }

  private async checkPowerPlan(): Promise<HealthIssue | null> {
    if (process.platform !== 'win32') return null
    const { stdout } = await this.deps.ps(
      `
      $scheme = [string](powercfg /getactivescheme)
      $battery = @(Get-CimInstance -ClassName Win32_Battery -ErrorAction SilentlyContinue).Count
      @{ scheme = $scheme; battery = $battery } | ConvertTo-Json -Compress
      `,
      15000
    )
    const start = stdout.indexOf('{')
    if (start < 0) return null
    const info = JSON.parse(stdout.slice(start)) as { scheme?: string; battery?: number }
    const scheme = String(info.scheme ?? '').toLowerCase()
    const isPowerSaver =
      scheme.includes(POWER_SAVER_PREFIX) || /power saver|ahorro de energ|economizador/.test(scheme)
    // On a laptop, saving battery is a legitimate choice: leave it alone.
    if (!isPowerSaver || Number(info.battery) > 0) return null

    return {
      id: 'power_saver',
      title: 'Tu PC está en modo de ahorro de energía',
      description:
        'Este modo limita la velocidad del procesador para gastar menos electricidad. ' +
        'En un PC de sobremesa no merece la pena: el modo "Equilibrado" de Windows es igual de seguro y bastante más rápido.',
      severity: 'warning',
      fixId: 'power_plan_balanced',
      fixLabel: 'Usar el modo Equilibrado',
      autoFix: true,
      benefit: 'PC más rápido',
      page: 'optimizer'
    }
  }

  private async checkDiskSpace(): Promise<HealthIssue | null> {
    const drive = await this.deps.getSystemDrive()
    if (!drive || drive.totalGB <= 0) return null
    const freePct = (drive.freeGB / drive.totalGB) * 100
    const freeText = `${drive.freeGB.toFixed(1).replace('.', ',')} GB`

    if (freePct < 5 || drive.freeGB < 5) {
      return {
        id: 'disk_space',
        title: `Queda muy poco espacio en el disco ${drive.drive}`,
        description:
          `Solo quedan ${freeText} libres. Con tan poco espacio Windows va lento y puede fallar al actualizarse. ` +
          'Borra los archivos temporales y mueve o elimina archivos grandes que no uses (vídeos, descargas antiguas…).',
        severity: 'critical',
        autoFix: false,
        page: 'cleanup'
      }
    }
    if (freePct < 10 || drive.freeGB < 15) {
      return {
        id: 'disk_space',
        title: `Poco espacio libre en el disco ${drive.drive}`,
        description:
          `Quedan ${freeText} libres. Conviene tener más margen para que Windows funcione con fluidez. ` +
          'Revisa la carpeta de Descargas y desinstala programas que ya no uses.',
        severity: 'warning',
        autoFix: false,
        page: 'cleanup'
      }
    }
    return null
  }

  private checkMemory(): HealthIssue | null {
    const { totalMB, freeMB } = this.deps.getMemory()
    if (!(totalMB > 0)) return null
    const usedPct = ((totalMB - freeMB) / totalMB) * 100
    if (usedPct < 85) return null
    return {
      id: 'memory_usage',
      title: 'La memoria del PC está casi llena',
      description:
        `Se está usando el ${Math.round(usedPct)} % de la memoria. Cierra los programas y pestañas del navegador ` +
        'que no estés usando para que el PC vaya más ágil. Tener menos programas al inicio también ayuda.',
      severity: usedPct >= 95 ? 'warning' : 'info',
      autoFix: false,
      page: 'startup'
    }
  }

  // ── One-click optimization ────────────────────────────────────────────────

  async smartOptimize(
    fixIds: SmartFixId[],
    onProgress: (p: SmartProgress) => void = () => undefined,
    onAction: (e: SmartActionEvent) => void = () => undefined
  ): Promise<SmartOptimizeResult> {
    const report = (step: string, percent: number): void => {
      try {
        onProgress({ step, percent: Math.max(0, Math.min(100, Math.round(percent))) })
      } catch {
        // A broken listener must never stop the optimization.
      }
    }
    const requested = SMART_FIX_IDS.filter((id) => fixIds.includes(id))
    const results: SmartFixResult[] = []
    let freedMB = 0

    // 1. Safety first: restore point.
    let restorePoint: RestorePointResult
    if (process.platform === 'win32' && this.deps.shouldCreateRestorePoint()) {
      report('Creando un punto de restauración de seguridad…', 2)
      try {
        restorePoint = await this.deps.restorePoint.create('NitroFlow: optimización en 1 clic')
      } catch (err) {
        restorePoint = { success: false, message: `No se pudo crear el punto de restauración: ${String(err)}` }
      }
    } else if (process.platform === 'win32') {
      restorePoint = {
        success: false,
        skipped: true,
        message: 'Los puntos de restauración están desactivados en Ajustes.'
      }
    } else {
      restorePoint = { success: true, message: 'Punto de restauración creado (modo demostración).' }
    }
    const protectedBySystemRestore = restorePoint.success
    report(restorePoint.success ? 'Copia de seguridad lista' : 'Continuando solo con cambios seguros', 20)

    // 2. Apply fixes one after another (they share disks and PowerShell).
    for (let i = 0; i < requested.length; i++) {
      const fixId = requested[i]
      const base = 20 + (80 * i) / requested.length
      report(STEP_LABELS[fixId], base)

      if (!protectedBySystemRestore && !SAFE_WITHOUT_RESTORE_POINT.has(fixId)) {
        results.push({
          fixId,
          success: false,
          skipped: true,
          message: 'No se aplicó porque no se pudo crear un punto de restauración.'
        })
        continue
      }

      let result: SmartFixResult
      try {
        result = await this.applyFix(fixId, onAction)
      } catch (err) {
        log.error(`HealthService: fix "${fixId}" failed:`, err)
        result = { fixId, success: false, message: `No se pudo completar: ${String(err)}` }
      }
      freedMB += result.freedMB ?? 0
      results.push(result)
    }

    // The disk contents changed: the next scan must measure again.
    this.lastCleanupScan = null
    report('¡Listo!', 100)
    return { restorePoint, results, freedMB: Math.round(freedMB * 10) / 10 }
  }

  private async applyFix(fixId: SmartFixId, onAction: (e: SmartActionEvent) => void): Promise<SmartFixResult> {
    switch (fixId) {
      case 'cleanup_safe':
        return this.fixCleanup(onAction)
      case 'empty_recycle_bin':
        return this.fixRecycleBin(onAction)
      case 'startup_disable_recommended':
        return this.fixStartup(onAction)
      case 'power_plan_balanced':
        return this.fixPowerPlan(onAction)
    }
  }

  private async fixCleanup(onAction: (e: SmartActionEvent) => void): Promise<SmartFixResult> {
    const ids = recommendedCategories(await this.getCleanupCategories())
      .filter((c) => c.sizeMB > 0)
      .map((c) => c.id)
    if (ids.length === 0) {
      return { fixId: 'cleanup_safe', success: true, skipped: true, freedMB: 0, message: 'No había archivos temporales que borrar.' }
    }
    const res = await this.deps.cleanup.clean(ids)
    const freed = sumFreed(res)
    if (freed > 0) onAction({ kind: 'cleanup', freedMB: freed, categoryIds: ids, label: 'Archivos temporales' })
    const needsAdmin = res.some((r) => r.requiresAdmin)
    const ok = res.some((r) => r.success || r.empty)
    return {
      fixId: 'cleanup_safe',
      success: ok,
      freedMB: freed,
      message: ok
        ? `Se han liberado ${formatSize(freed)} de archivos temporales.` +
          (needsAdmin ? ' Algunos archivos de Windows necesitan permisos de administrador.' : '')
        : 'No se pudieron borrar los archivos temporales (puede que estén en uso).'
    }
  }

  private async fixRecycleBin(onAction: (e: SmartActionEvent) => void): Promise<SmartFixResult> {
    const res = await this.deps.cleanup.clean(['recycle_bin'])
    const freed = sumFreed(res)
    const ok = res.length > 0 && res.every((r) => r.success || r.empty)
    if (ok) onAction({ kind: 'cleanup', freedMB: freed, categoryIds: ['recycle_bin'], label: 'Papelera de reciclaje' })
    return {
      fixId: 'empty_recycle_bin',
      success: ok,
      freedMB: freed,
      message: ok ? `Papelera vaciada (${formatSize(freed)}).` : 'No se pudo vaciar la papelera.'
    }
  }

  private async fixStartup(onAction: (e: SmartActionEvent) => void): Promise<SmartFixResult> {
    // Always re-read: the user may have changed something since the scan.
    const candidates = disableCandidates(await this.deps.startup.listEntries())
    if (candidates.length === 0) {
      return {
        fixId: 'startup_disable_recommended',
        success: true,
        skipped: true,
        count: 0,
        message: 'No había programas de inicio que desactivar.'
      }
    }
    const disabled: string[] = []
    const failed: string[] = []
    for (const entry of candidates) {
      const r = await this.deps.startup.toggleEntry(entry.id, false)
      if (r.success) {
        disabled.push(entry.name)
        onAction({ kind: 'startup', id: entry.id, name: entry.name })
      } else {
        failed.push(entry.name)
      }
    }
    const n = disabled.length
    let message =
      n === 0
        ? 'No se pudo desactivar ningún programa de inicio.'
        : n === 1
          ? `Se desactivó 1 programa de inicio (${disabled[0]}).`
          : `Se desactivaron ${n} programas de inicio (${listNames(disabled)}).`
    if (n > 0 && failed.length > 0) message += ` No se pudo con: ${listNames(failed)}.`
    return { fixId: 'startup_disable_recommended', success: n > 0, count: n, message }
  }

  private async fixPowerPlan(onAction: (e: SmartActionEvent) => void): Promise<SmartFixResult> {
    if (process.platform !== 'win32') {
      onAction({ kind: 'power_plan' })
      return { fixId: 'power_plan_balanced', success: true, message: 'Modo de energía "Equilibrado" activado.' }
    }
    // powercfg reports most failures through its exit code (and stdout), not
    // stderr: without this check a failed switch was shown as a success.
    const result = await this.deps.ps(
      `$out = powercfg /setactive ${POWER_PLAN_BALANCED} 2>&1 | Out-String
      if ($LASTEXITCODE -ne 0) { [Console]::Error.WriteLine("powercfg: " + $out.Trim()) }`,
      15000
    )
    if (!result.ok) {
      return {
        fixId: 'power_plan_balanced',
        success: false,
        message: `No se pudo cambiar el modo de energía: ${describePowerShellError(result.stderr)}`
      }
    }
    onAction({ kind: 'power_plan' })
    return { fixId: 'power_plan_balanced', success: true, message: 'Modo de energía "Equilibrado" activado.' }
  }
}

const STEP_LABELS: Record<SmartFixId, string> = {
  cleanup_safe: 'Borrando archivos temporales…',
  empty_recycle_bin: 'Vaciando la papelera…',
  startup_disable_recommended: 'Desactivando programas innecesarios al inicio…',
  power_plan_balanced: 'Ajustando el modo de energía…'
}

function sumFreed(results: CleanupResult[]): number {
  return Math.round(results.reduce((sum, r) => sum + (Number(r.freedMB) || 0), 0) * 10) / 10
}

export function computeScore(issues: HealthIssue[]): number {
  const penalty = issues.reduce((sum, i) => sum + SEVERITY_PENALTY[i.severity], 0)
  return Math.max(0, Math.min(100, 100 - penalty))
}

function buildSummary(score: number, issues: HealthIssue[]): string {
  if (issues.length === 0) {
    return 'Tu PC está en buen estado. No hemos encontrado nada que mejorar.'
  }
  const fixable = issues.filter((i) => i.autoFix && i.fixId).length
  const critical = issues.some((i) => i.severity === 'critical')
  const parts: string[] = []
  if (score >= 85) parts.push('Tu PC está en buen estado.')
  else if (score >= 60) parts.push('Tu PC puede ir más rápido.')
  else parts.push('Tu PC necesita un poco de atención.')

  if (fixable > 0) {
    parts.push(
      fixable === 1
        ? 'Hemos encontrado 1 mejora que podemos aplicar por ti de forma segura.'
        : `Hemos encontrado ${fixable} mejoras que podemos aplicar por ti de forma segura.`
    )
  } else {
    parts.push(issues.length === 1 ? 'Tenemos un consejo para ti.' : `Tenemos ${issues.length} consejos para ti.`)
  }
  if (critical) parts.push('Hay un aviso importante que conviene revisar.')
  return parts.join(' ')
}
